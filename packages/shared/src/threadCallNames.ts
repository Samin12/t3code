export function pickThreadCallName(threadId: string, occupied: Iterable<string>): string {
  let hash = 2166136261;
  for (const character of threadId) {
    hash = Math.imul(hash ^ character.charCodeAt(0), 16777619) >>> 0;
  }
  const used = new Set(Array.from(occupied, (name) => name.toLowerCase()));
  for (let suffix = 1; ; suffix++) {
    for (let offset = 0; offset < THREAD_CALL_NAMES.length; offset++) {
      const base = THREAD_CALL_NAMES[(hash + offset) % THREAD_CALL_NAMES.length]!;
      const candidate = suffix === 1 ? base : `${base} ${suffix}`;
      if (!used.has(candidate.toLowerCase())) return candidate;
    }
  }
}
